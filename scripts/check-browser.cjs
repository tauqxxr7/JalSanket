// Controlled failure fixtures are test-only, never real telemetry.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const baseUrl = process.env.JALSANKET_BASE_URL || 'http://127.0.0.1:8766';
(async () => {
  const output = path.join(__dirname, '../artifacts');
  await fs.mkdir(output, {recursive:true});
  const browser = await chromium.launch({channel:'chrome', headless:true, chromiumSandbox:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];
    page.on('pageerror', error=>errors.push(String(error)));
    await page.goto(baseUrl+'/',{waitUntil:'networkidle'});
    assert.equal(await page.locator('.queue-row').count(),5);
    assert.equal(await page.locator('#flag-count').textContent(),'0');
    assert.equal(await page.locator('#environment-count').textContent(),'0');
    await page.getByRole('button',{name:'Open station Ambhasi',exact:true}).click();
    await page.getByRole('heading',{name:'Ambhasi · Buldana, Maharashtra',exact:true}).waitFor();
    assert.equal(await page.locator('.history-chart circle').count(),356);
    assert.match(await page.locator('#station-view').innerText(),/Original signs preserved/);
    await page.getByRole('link',{name:'VIEW EVIDENCE →',exact:true}).click();
    await page.getByRole('heading',{name:'Ambhasi · Evidence Trail',exact:true}).waitFor();
    assert.match(await page.locator('.assessment').innerText(),/UNCERTAIN — ABSTAIN/);
    assert.match(await page.locator('.next-check').innerText(),/independent reference measurement/);
    await page.getByText('Data quality & detector eligibility',{exact:true}).click();
    assert.match(await page.locator('#quality').innerText(),/SPIKE: ELIGIBLE/);
    await page.getByText('Source provenance & original evidence rows',{exact:true}).click();
    assert.equal(await page.locator('#evidence tbody tr').count(),29);
    assert.match(await page.locator('#evidence tbody').innerText(),/-14.22/);
    await page.screenshot({path:path.join(output,'evidence-desktop.png'),fullPage:true});
    await page.reload({waitUntil:'networkidle'});
    await page.getByRole('heading',{name:'Ambhasi · Evidence Trail',exact:true}).waitFor();
    await page.getByRole('link',{name:'← STATION DETAIL',exact:true}).click();
    await page.getByRole('heading',{name:'Ambhasi · Buldana, Maharashtra',exact:true}).waitFor();
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.getByRole('link',{name:'VIEW EVIDENCE →',exact:true}).click();
    await page.getByRole('heading',{name:'Ambhasi · Evidence Trail',exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.getByRole('link',{name:'Network overview',exact:true}).click();
    await page.locator('#station-filter').fill('no-such-station');
    assert.match(await page.locator('#queue-list').innerText(),/No stations match/);
    await page.locator('#station-filter').fill('Ambhasi');
    await page.getByRole('button',{name:'Open station Ambhasi',exact:true}).press('Enter');
    await page.getByRole('heading',{name:'Ambhasi · Buldana, Maharashtra',exact:true}).waitFor();
    await page.getByRole('link',{name:'← NETWORK OVERVIEW',exact:true}).click();
    assert.equal(await page.locator('.queue-row').count(),1);
    await page.route('**/api/network',route=>route.fulfill({status:503,json:{detail:'Controlled outage'}}));
    await page.reload({waitUntil:'networkidle'});
    assert.equal(await page.locator('#error').isVisible(),true);
    assert.equal(await page.locator('#station-count').textContent(),'—');
    await page.unroute('**/api/network');
    await page.getByRole('button',{name:'Retry connection'}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.queue-row').length===5);
    await page.route('**/api/stations/*',route=>route.fulfill({status:500,json:{detail:'Controlled failure'}}));
    await page.getByRole('button',{name:'Open station Ambhasi',exact:true}).click();
    await page.getByRole('heading',{name:'Station unavailable',exact:true}).waitFor();
    await page.unroute('**/api/stations/*');
    assert.deepEqual(errors,[]);
    const report={status:'PASS',checks:['official API → Network → Station history → Evidence → abstention → next check','356 source points and 29 evidence rows','deep-link refresh and back navigation','keyboard/filter/empty states','390px Station/Evidence overflow','503 and retry','500 station failure'],page_errors:errors};
    await fs.writeFile(path.join(output,'browser-report.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
